rows = []

def verdict(lo, hi, m):
    if lo > -m and hi < m:
        return "EQUIV"
    if hi <= -m:
        return "L worse"
    if lo >= m:
        return "L better"
    return "no"

def add(id_, setting, cls_name, L_name, c, L, flag, rel=False):
    c = np.asarray(c, float); L = np.asarray(L, float)
    n = len(c)
    if rel:  # relative RMSE difference, positive = learned worse
        base = c.mean()
        d, l90, h90 = boot_diff(c, L, 5, 95); _, l95, h95 = boot_diff(c, L)  # (C - L): positive = learned better (lower RMSE)
        scale = 100.0 / base
        cm, lm, unit = c.mean(), L.mean(), "RMSE"
        cs = f"{cm:.4f}"; ls_ = f"{lm:.4f}"
    else:
        d, l90, h90 = boot_diff(L, c, 5, 95); _, l95, h95 = boot_diff(L, c)
        scale = 100.0
        cs = f"{100*c.mean():.1f}"; ls_ = f"{100*L.mean():.1f}"
    v10 = verdict(scale*l90, scale*h90, 10); v5 = verdict(scale*l90, scale*h90, 5)
    P(f"| {id_} | {setting} | {cls_name} | {L_name} | {n} | {cs} | {ls_} | {scale*d:+.1f} [{scale*l90:+.1f}, {scale*h90:+.1f}] | [{scale*l95:+.1f}, {scale*h95:+.1f}] | {v10} | {v5} | {flag} |")
    rows.append((id_, L_name, v10, v5))

