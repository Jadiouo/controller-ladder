B = 10000
rng = np.random.default_rng(0)

def idx(n):
    return rng.integers(0, n, size=(B, n))

def boot_diff(a, b, lo=2.5, hi=97.5):
    """paired mean(a)-mean(b) with percentile CI"""
    d = np.asarray(a, float) - np.asarray(b, float)
    ix = idx(len(d))
    m = d[ix].mean(1)
    return d.mean(), np.percentile(m, lo), np.percentile(m, hi)

def recovered(L, R0, R1, lo=2.5, hi=97.5):
    L, R0, R1 = map(lambda x: np.asarray(x, float), (L, R0, R1))
    ix = idx(len(L))
    num = L[ix].mean(1) - R0[ix].mean(1)
    den = R1[ix].mean(1) - R0[ix].mean(1)
    with np.errstate(divide="ignore", invalid="ignore"):
        rf = num / den
    global NBAD
    NBAD = int((den <= 0).sum())
    pt = (L.mean() - R0.mean()) / (R1.mean() - R0.mean())
    return pt, np.percentile(rf, lo), np.percentile(rf, hi), np.percentile(den, 2.5), np.percentile(den, 97.5)

