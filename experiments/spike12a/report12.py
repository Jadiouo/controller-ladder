"""spike12a: assemble results/spike12a/table.md from final.json / cal.json / spread.json / disp.json / latency.json / selection.json (no new simulation).
Each (student, dataset) cell = mean over the available training seeds (per-episode success averaged over seeds, then bootstrapped over the 200 episodes)."""
import json, os, numpy as np
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'results', 'spike12a'); L = lambda n: json.load(open(os.path.join(R, n))) if os.path.exists(os.path.join(R, n)) else {}
def ci(x, n=20000, seed=0):
    x = np.asarray(x, float); r = np.random.default_rng(seed); b = x[r.integers(0, len(x), (n, len(x)))].mean(1); return np.quantile(b, .025), np.quantile(b, .975)
def pct(v): return f'{100 * v:.1f}'
def diff(a, b, seed=1):
    d = np.asarray(a, float) - np.asarray(b, float); lo, hi = ci(d, seed=seed); return f'{100 * d.mean():+.1f} pp [{100 * lo:+.1f}, {100 * hi:+.1f}]', 100 * lo, 100 * hi, 100 * d.mean()
fin, cal, sp, dp, lat, sel = L('final.json'), L('cal.json'), L('spread.json'), L('disp.json'), L('latency.json'), L('selection.json')
KINDS = [('bc', 'MLP regression (BC)'), ('mip', 'MIP (2-step regression)'), ('diffusion', 'Diffusion DDIM-10'), ('flow', 'Flow 10 steps'), ('flow1', 'Flow 1 step')]
def seeds_of(k, d): return [n for n in (f'{k}_{d}', f'{k}_{d}_s1', f'{k}_{d}_s2') if n in fin]
def arr(k, d):
    s = seeds_of(k, d); return np.mean([fin[n]['per_seed'] for n in s], 0) if s else None
def fmt(k, d):
    s = seeds_of(k, d)
    if not s: return '-'
    a = arr(k, d); lo, hi = ci(a); per = ' / '.join(pct(fin[n]['succ']) for n in s); return f'{pct(a.mean())} [{pct(lo)}, {pct(hi)}] (seeds: {per})'
out = ['# spike12a tables (generated by experiments/spike12a/report12.py)', '', 'Final set: seeds 700200-700399 (n=200, never used before). Cell = mean over training seeds (per-seed values listed), bootstrap CI over the 200 episodes. Checkpoint per seed picked on CAL1+CAL2 (n=100).', '']
out += ['## 1. Main table (new seeds, success %)', '', '| student | params | D-multi | D-canon |', '|---|---|---|---|']
for k, nm in KINDS: out.append(f"| {nm} | {sel.get(f'{k}_multi', {}).get('params', '')} | {fmt(k, 'multi')} | {fmt(k, 'canon')} |")
for k in ('oracle_canon', 'adapt3full', 'nom'):
    if k in fin: out.append(f"| baseline {k} | - | {pct(fin[k]['succ'])} [{pct(fin[k]['ci'][0])}, {pct(fin[k]['ci'][1])}] | |")
out += ['', '## 2. Paired differences (same 200 seeds; cells are seed-averaged)', '', '| comparison | diff [95% CI] |', '|---|---|']
rule = {}
for d in ('multi', 'canon'):
    mlp = arr('bc', d)
    for k, nm in KINDS[1:]:
        c = arr(k, d)
        if c is not None and mlp is not None: s = diff(c, mlp); out.append(f'| {nm} - MLP, D-{d} | {s[0]} |'); rule[(k, d)] = s
out += ['', '| generative on D-multi vs MLP on D-canon | diff |', '|---|---|']
for k, nm in KINDS[2:]:
    if arr(k, 'multi') is not None and arr('bc', 'canon') is not None: out.append(f"| {nm} (D-multi) - MLP (D-canon) | {diff(arr(k, 'multi'), arr('bc', 'canon'))[0]} |")
out += ['', '| cell | vs D-canon same student (D-multi minus D-canon) |', '|---|---|']
for k, nm in KINDS:
    if arr(k, 'multi') is not None and arr(k, 'canon') is not None: out.append(f"| {nm} | {diff(arr(k, 'multi'), arr(k, 'canon'))[0]} |")
if 'adapt3full' in fin:
    A = fin['adapt3full']['per_seed']; out += ['', '| cell | minus T-adapt3-full |', '|---|---|']
    for d in ('multi', 'canon'):
        for k, nm in KINDS:
            if arr(k, d) is not None: out.append(f'| {nm} D-{d} | {diff(arr(k, d), A)[0]} |')
if 'oracle_canon' in fin:
    out += ['', '| cell | minus T-oracle(canon) |', '|---|---|']
    for d in ('multi', 'canon'):
        for k, nm in KINDS:
            if arr(k, d) is not None: out.append(f"| {nm} D-{d} | {diff(arr(k, d), fin['oracle_canon']['per_seed'])[0]} |")
gen = [k for k in ('diffusion', 'flow', 'flow1') if arr(k, 'multi') is not None]
if gen:
    best = max(gen, key=lambda k: arr(k, 'multi').mean()); s = rule[(best, 'multi')]
    out += ['', f'## 3. Pre-registered primary rule (best generative on D-multi vs MLP, >= +10 pp and CI excludes 0)', '', f'best generative by final mean (selection on the final set is optimistic): {best}; diff = {s[0]}; rule met: {bool(s[3] >= 10 and s[1] > 0)}']
if cal: out += ['', '## 4. CAL (1000-1099, n=100) for every checkpoint', '', '| name | success % [CI] |', '|---|---|'] + [f"| {k} | {pct(v['succ'])} [{pct(v['ci'][0])}, {pct(v['ci'][1])}] |" for k, v in cal.items()]
if sp: out += ['', '## 5. Closed-loop plan spread (RMS between 4 noise draws of the executed reference, 40 CAL scenarios, rad; seed 0 models)', '', '| model | rms |', '|---|---|'] + [f"| {k} | {v['rms_between_noise_draws_rad']:.3f} |" for k, v in sp.items()]
if dp: out += ['', '## 6. Same-observation dispersion (16 samples, held-out multi scenarios, std over samples of qr-residual chunk, rad, at step k=0/25/50/100; teacher_spread = std across 4 teacher plans of the same scenario)', '', '```', json.dumps(dp), '```']
if lat: out += ['', '## 7. Inference latency (CPU, 1 thread, ms per chunk of 16; amortised per control step = /8; measured while other jobs loaded the machine)', '', '```', json.dumps(lat), '```']
open(os.path.join(R, 'table.md'), 'w').write('\n'.join(out) + '\n'); print('\n'.join(out))
