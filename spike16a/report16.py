"""Builds results/spike16a/table.md from the per-task json files (verdict rules: README section 0.6)."""
import sys, os, json; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'results', 'spike16a')
def holm(p):
    p = np.asarray(p, float); o = np.argsort(p); out = np.zeros_like(p); run = 0
    for i, j in enumerate(o): run = max(run, min(1.0, (len(p) - i) * p[j])); out[j] = run
    return out
SUF = os.environ.get('S16_SUFFIX', ''); tasks = ['catch', 'toss', 'push_t'] if not SUF else [x.strip() for x in os.environ['S16_TASKS'].split(',')]; R = {}; L = ['# spike16a table (generated by spike16a/report16.py)', '']
for t in tasks:
    d = os.path.join(RES, t + SUF); r = {}
    for k in ('calib_s', 'classical', 'gate', 'real'):
        f = os.path.join(d, k + '.json'); r[k] = json.load(open(f)) if os.path.exists(f) else None
    R[t] = r
L += ['## Setup', '', '| task | s (strength) | strongest classical | CAL success (tuning set) | tuning episodes / wall | gate bias (Nm) | gate status |', '|---|---|---|---|---|---|---|']
for t in tasks:
    c, g = R[t]['classical'], R[t]['gate']
    L.append(f"| {t} | {c['s'] if c else '-'} | {c['strongest'] if c else '-'} | {c['succ_cal']:.3f} ({c['tuning_set']}) | {c['tuning_episodes']} / {c['tuning_wall_s']/60:.0f} min |" if c else f"| {t} | - | - | - | - |")
    L[-1] += (f" {g['bias']}{' (fallback)' if g.get('bias_fallback') else ''} | {g.get('gate_status', 'running')} |" if g else " - | - |")
L += ['', '## Gate tests (GATE seeds 706000-706299, bias on, paired learned - zero-residual init)', '', '| task | run | init | learned | diff [95% CI] | pass |', '|---|---|---|---|---|---|']
for t in tasks:
    g = R[t]['gate']
    for x in (g or {}).get('gate_tests', []): L.append(f"| {t} | {x['tag']} | {x['init']:.3f} | {x['rl']:.3f} | {100*x['diff']:+.1f} [{100*x['lo95']:+.1f}, {100*x['hi95']:+.1f}] pp | {x['passed']} |")
ps = [R[t]['real']['sets']['hold']['p_gt0'] if R[t]['real'] else 1.0 for t in tasks]; ph = holm(ps)
L += ['', '## Real condition: learned (residual PPO on the strongest classical, pooled over the trained seeds) minus classical', '', '| task | set | n | classical | learned | diff [95% CI] pp | 90% CI pp | residual mean (Nm) |', '|---|---|---|---|---|---|---|---|']
V = {}
for i, t in enumerate(tasks):
    r = R[t]['real']
    if not r: V[t] = 'NOT RUN (gate ' + (R[t]['gate'].get('gate_status', 'running') if R[t]['gate'] else 'missing') + ')'; continue
    ok_win, ok_tie, ok_cb = True, True, True
    for name in ('hold', 'new'):
        x = r['sets'][name]; res = np.mean([v['res'] for v in x['per_seed'].values()])
        L.append(f"| {t} | {name} | {x['n']} | {x['classical']:.3f} | {x['learned']:.3f} | {100*x['diff']:+.1f} [{100*x['lo95']:+.1f}, {100*x['hi95']:+.1f}] | [{100*x['lo90']:+.1f}, {100*x['hi90']:+.1f}] | {res:.2f} |")
        ok_win &= (x['diff'] >= 0.10 and x['lo95'] > 0); ok_tie &= (x['lo90'] >= -0.10 and x['hi90'] <= 0.10); ok_cb &= (x['hi95'] < 0)
    v = 'LEARNED WINS' if ok_win else 'TIE' if ok_tie else 'UNCERTAIN'
    if r.get('descriptive_only_gate_failed'): v = 'DESCRIPTIVE ONLY (gate failed; not a verdict): would read ' + v
    if ok_win and ph[i] >= 0.05: v += ' (not Holm-robust)'
    if ok_cb: v += ' [descriptive: classical better]'
    V[t] = v
L += ['', '## Verdicts', '', '| task | verdict | Holm-adjusted p (HOLD win test) |', '|---|---|---|']
for i, t in enumerate(tasks): L.append(f"| {t} | {V[t]} | {ph[i]:.3f} |")
L += ['', '## Per-seed (HOLD)', '', '| task | seed | learned | diff [95% CI] pp | residual (Nm) | selected ckpt CAL-S |', '|---|---|---|---|---|---|']
for t in tasks:
    r = R[t]['real']
    if not r: continue
    for sd, x in r['per_seed'].items() if False else r['sets']['hold']['per_seed'].items():
        L.append(f"| {t} | {sd} | {x['succ']:.3f} | {100*x['diff']:+.1f} [{100*x['lo95']:+.1f}, {100*x['hi95']:+.1f}] | {x['res']:.2f} | {r['budget'][sd]['selected']['succ']:.3f} (init {r['budget'][sd]['init_cal_s']:.3f}) |")
L += ['', '## Budget (three axes)', '', '| task | method | episodes | control steps | wall clock | label source |', '|---|---|---|---|---|---|']
for t in tasks:
    c, r = R[t]['classical'], R[t]['real']
    if c: L.append(f"| {t} | classical tuning (ES) | {c['tuning_episodes']} | - | {c['tuning_wall_s']/60:.0f} min | simulator success flag + smooth term, no gradients |")
    if r:
        for sd, b in r['budget'].items(): L.append(f"| {t} | residual PPO seed {sd} | {b['total_episodes']} (train {b['train_episodes']} + CAL-S {b['cal_eval_episodes']}) | {b['control_steps']:.2e} | {b['wall_s']/60:.0f} min | privileged simulator state in reward only |")
open(os.path.join(RES, 'table' + SUF + '.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))
