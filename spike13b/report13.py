"""assemble results/spike13b/table.md from raw json (no simulation)"""
import sys, os, json, numpy as np; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'results', 'spike13b'); L = lambda n: json.load(open(os.path.join(R, n))) if os.path.exists(os.path.join(R, n)) else {}
def ci(x, n=20000, seed=0):
    x = np.asarray(x, float); r = np.random.default_rng(seed); b = x[r.integers(0, len(x), (n, len(x)))].mean(1); return np.quantile(b, .025), np.quantile(b, .975)
def fm(x): x = np.asarray(x, float); lo, hi = ci(x); return f'{100*x.mean():.1f} [{100*lo:.1f}, {100*hi:.1f}]'
def fd(a, b): d = np.asarray(a, float) - np.asarray(b, float); lo, hi = ci(d, seed=1); return f'{100*d.mean():+.1f} [{100*lo:+.1f}, {100*hi:+.1f}]'
NAMES = [('adapt3_full', 'R0 T-adapt3-full'), ('R1', 'R1 true theta (probe+replay state)'), ('R2', 'R2 R1 + true chain state'), ('R3', 'R3 oracle, rest, waits 0.6 s'), ('oracle', 'R4 T-oracle (t=0, full horizon)'), ('R5', 'R5 canonical T-oracle')]
def get(res, m, cond='abc'):
    if m == 'lest': 
        v = [res[f'lest_full#{s}|{cond}']['success'] for s in range(3) if f'lest_full#{s}|{cond}' in res]
        return np.mean(v, 0) if len(v) == 3 else None
    k = f'{m}|{cond}'; return np.array(res[k]['success']) if k in res else None
out = ['# spike13b tables (generated by spike13b/report13.py)', '']
for fn, lab in (('ladder_hold.json', 'holdout 1100-1599 (n=500)'), ('ladder_new.json', 'new seeds 700600-700799 (n=200)')):
    res = L(fn)
    if not res: continue
    out += [f'## Ladder, {lab}', '', '| rung | success % [95% CI] | step (paired diff vs rung above) pp [95% CI] | vs R0 |', '|---|---|---|---|']; prev = None; r0 = get(res, 'adapt3_full')
    for m, nm in NAMES:
        x = get(res, m)
        if x is None: continue
        out.append(f"| {nm} | {fm(x)} | {fd(x, prev) if prev is not None else '-'} | {fd(x, r0) if m != 'adapt3_full' else '-'} |"); prev = x
    le = get(res, 'lest')
    if le is not None:
        out.append(f"| L-est-full (mean of 3 models per seed) | {fm(le)} | - | {fd(le, r0)} |"); r1 = get(res, 'R1')
        if r1 is not None: out.append(f"| (L-est-full minus R1) | | | {fd(le, r1)} |")
        for s in range(3): out.append(f"| L-est-full model #{s} | {fm(res[f'lest_full#{s}|abc']['success'])} | - | {fd(res[f'lest_full#{s}|abc']['success'], r0)} |")
    xs = [get(res, m) for m, _ in NAMES]
    if all(x is not None for x in xs):
        out += ['', f"Totals: R4 - R0 = {fd(xs[4], xs[0])} pp; R5 - R0 = {fd(xs[5], xs[0])} pp; R2 - R0 (all estimation-side) = {fd(xs[2], xs[0])} pp; R4 - R2 (probe cost: start state + time) = {fd(xs[4], xs[2])} pp.", '']
    inst = {k: float(np.mean(np.array(v['inst']) > 0)) for k, v in res.items()}; out.append('Unstable-episode fraction (any plant blow-up) per method: ' + ', '.join(f'{k.split("|")[0]} {100*v:.1f}%' for k, v in inst.items())); out.append('')
sw = L('sweep.json')
if sw:
    mults = [0.5, 1, 2, 4, 8]; meths = [('nom', 'T-nom'), ('robust', 'T-robust'), ('adapt3_full', 'T-adapt3-full'), ('lestcyc', 'L-est-full'), ('oracle', 'T-oracle')]
    def cn(f, m): return 'abc' if m == 1 else f'abc_{f}{m}'
    def drop10(vals):
        base = vals[1]; xs = np.log2([1, 2, 4, 8]); ys = [vals[i] for i in (1, 2, 3, 4)]
        for i in range(1, 4):
            if ys[i] <= base - 0.10:
                a, b = ys[i - 1], ys[i]; f = (a - (base - 0.10)) / (a - b) if a != b else 0; return f'{2 ** (xs[i-1] + f * (xs[i] - xs[i-1])):.2f}'
        return '>8'
    for f, lab in (('a', 'sensor noise (arm q, qd) multiplier'), ('c', 'actuator noise multiplier')):
        out += [f'## Fragility sweep: {lab}  (seeds 1100-1299, n=200; success % [95% CI])', '', '| method | x0.5 | x1 | x2 | x4 | x8 | drop-10pp multiplier |', '|---|---|---|---|---|---|---|']
        for m, nm in meths:
            xs = [get(sw, m, cn(f, mm)) for mm in mults]
            if any(x is None for x in xs): continue
            out.append(f"| {nm} | " + ' | '.join(fm(x) for x in xs) + f" | {drop10([x.mean() for x in xs])} |")
        out += ['', 'Paired drop vs x1 (pp [CI]):', '', '| method | x2 | x4 | x8 |', '|---|---|---|---|']
        for m, nm in meths:
            xs = [get(sw, m, cn(f, mm)) for mm in mults]
            if any(x is None for x in xs): continue
            out.append(f"| {nm} | " + ' | '.join(fd(xs[i], xs[1]) for i in (2, 3, 4)) + ' |')
        out.append('')
hy = L('hybrid.json'); lh = L('ladder_hold.json')
if hy and lh:
    r0, r1 = get(lh, 'adapt3_full'), get(lh, 'R1'); out += ['## Supplementary (post hoc) split of R0 -> R1 by parameter group, holdout 1100-1599 (n=500)', '', 'H_in = fitted theta with that group set to truth; H_out = true theta with that group set to the fit.', '', '| group | H_in success % | H_in - R0 | H_out success % | R1 - H_out (cost of only this group wrong) |', '|---|---|---|---|---|']
    for g, nm in (('ls', 'length scale'), ('m', '10 per-link masses'), ('ds', 'viscous damping'), ('fr', 'Coulomb friction')):
        a, b = get(hy, f'H_in_{g}'), get(hy, f'H_out_{g}')
        if a is not None and b is not None: out.append(f"| {nm} | {fm(a)} | {fd(a, r0)} | {fm(b)} | {fd(r1, b)} |")
    out.append('')
ps = L('probe_state.json')
if ps: out += ['## Exploratory ridge probe (does arm probe history linearly contain chain state / theta?)', '', '```', json.dumps({k: v for k, v in ps.items() if 'lam' not in k or 'ridge_probe' in k}, indent=1), '```', '']
open(os.path.join(R, 'table.md'), 'w').write('\n'.join(out)); print('\n'.join(out))
