"""Generate results/spike15b/table.md from the json files of spike15b (S6, S5, S3)."""
import json, os, glob, pickle, numpy as np
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')); R = os.path.join(ROOT, 'results/spike15b')
def J(p):
    p = os.path.join(R, p); return json.load(open(p)) if os.path.exists(p) else None
def pp(x): return f'{100*x:+.1f}'
def ci(d): return f"{pp(d['diff'])} [{pp(d['ci'][0])}, {pp(d['ci'][1])}]"
L = ['# spike15b table (generated by spike15b/report15.py)', '']
def real_block(name, prefix, tag, extra=''):
    L.append(f'### {name}'); L.append('')
    L.append('| set | n | init = best classical (%) | seed | CAL init -> selected (%) | selected ckpt it | RL (%) | diff vs init pp [95% CI] | residual mean (Nm) |'); L.append('|---|---|---|---|---|---|---|---|---|')
    for st in ('holdout', 'fresh'):
        d = J(f'{prefix}_eval_{tag}_{st}.json')
        if not d: continue
        for s, v in d['seeds'].items():
            cs = v['cal_sel']; ci0 = v['cal_init']
            L.append(f"| {st} | {d['n']} | {100*d['init']:.1f} | {s} | {100*ci0:.1f} -> {100*cs:.1f} | {v['selected_it']} | {100*v['succ']:.1f} | {ci(v)} | {v['res_mean']:.2f} |")
        p = d['pooled']; L.append(f"| **{st} pooled** | {d['n']} | {100*d['init']:.1f} | 0,1,2 | | | {100*p['succ']:.1f} | **{ci(p)}** | |")
    L.append('')
def gate_block(name, prefix, tag, calib):
    L.append(f'### {name}'); L.append('')
    c = J(calib)
    if c: L.append('Bias calibration (zero-residual success on CAL-A n=50): ' + ', '.join(f'b={k}: {100*(v if not isinstance(v, dict) else v["frac_cap"]):.0f}%' for k, v in c.items())); L.append('')
    d = J(f'{prefix}_eval_{tag}_gate.json')
    if d:
        for s, v in d['seeds'].items(): L.append(f"Gate run {tag} (seed {s}): CAL init {100*v['cal_init']:.1f} -> selected {100*v['cal_sel']:.1f} (it {v['selected_it']}); gate seeds n={d['n']}, bias {d['bias']:g}: init {100*d['init']:.1f}%, RL {100*v['succ']:.1f}%, diff {ci(v)} pp, residual {v['res_mean']:.2f} Nm.")
    L.append('')
L.append('## S6 (whip, idealised, base T-adapt)'); L.append('')
gate_block('S6 gate', 's6', 'gate_ls-1.5', 's6_gate_calib.json'); real_block('S6 real condition (log-std0 -1.5, 3 M steps, 3 seeds)', 's6', 'real_ls-1.5')
if J('s6_eval_nom_ls-1.5_holdout.json'): real_block('S6-X1 (descriptive, not in verdict): same recipe on the weak base T-nom (headroom exists)', 's6', 'nom_ls-1.5')
L.append('## S5 (juggling, distribution C, base T-robust(spike06))'); L.append('')
gate_block('S5 gate', 's5', 'gate_ls-2.0', 's5_gate_calib.json'); real_block('S5 real condition (log-std0 -2.0, 2.5 M steps, 3 seeds)', 's5', 'real_ls-2.0')
open(os.path.join(R, 'table.md'), 'w').write('\n'.join(L)); print('\n'.join(L))
# ---------------------------------------------------------------- S3
VARIANTS = ["bc", "mip", "diffusion (DDIM-10)", "flow (10 steps)", "flow (1 step)"]
def relboot(s, t, B=10000, seed=0):
    r = np.random.default_rng(seed); n = len(t); idx = r.integers(0, n, (B, n)); ts = t[idx].mean(1); rel = (s[idx].mean(1) - ts) / ts
    return float((s.mean() - t.mean()) / t.mean()), float(np.percentile(rel, 2.5)), float(np.percentile(rel, 97.5))
def label3(m, lo, hi):
    if hi < 0 and m <= -0.10: return 'WIN'
    if lo > -0.10 and hi < 0.10: return 'MATCH (CI inside +-10%)'
    if lo > 0.10: return 'WORSE (>10%)'
    if lo > 0: return 'worse (CI excludes 0, not > 10%)'
    return 'INCONCLUSIVE'
L2 = ['', '## S3 (tracking/clean, imitation students vs ctc_lqr teacher; fixed reference; TEST untouched)', '']
sel = J('s3/selected.json'); cal = J('s3/cal_eval.json')
if sel:
    L2 += ['CAL selection (rmse on CAL 1000-1049, 1 training seed, main variant of each kind). Teacher CAL rmse %.5f.' % np.mean(cal['teacher']['rmse']), '', '| kind | selected DART sigma | selected lr | CAL rmse | all 6 configs (rmse, dart, lr) |', '|---|---|---|---|---|']
    for k, v in sel.items(): L2.append(f"| {k} | {v['dart']} | {v['lr']:g} | {v['cal_rmse']:.5f} | " + '; '.join(f'{g[0]:.5f},{g[1]},{g[2]:g}' for g in v['grid']) + ' |')
    L2.append('')
ts = J('s3/train_summary.json')
for st in ('holdout', 'fresh'):
    res = J(f's3/final_{st}.json')
    if not res: continue
    t = np.array(res['teacher']['rmse']); L2 += [f'### {st} (n={len(t)})', '', f'Teacher rmse {t.mean():.5f}, ss_rmse {np.mean(res["teacher"]["ss_rmse"]):.5f}, failures {sum(o != "timeout" for o in res["teacher"]["outcome"])}.', '',
        '| student | rmse per training seed | rmse mean +- sd | ss_rmse | student - teacher, relative [95% CI] (paired, seed-averaged) | verdict | failures |', '|---|---|---|---|---|---|---|']
    for v in VARIANTS:
        if f'{v}|0' not in res: continue
        per = [np.mean(res[f'{v}|{s}']['rmse']) for s in (0, 1, 2) if f'{v}|{s}' in res]; avg = np.mean([res[f'{v}|{s}']['rmse'] for s in (0, 1, 2) if f'{v}|{s}' in res], 0); m, lo, hi = relboot(avg, t)
        ss = np.mean([np.mean(res[f'{v}|{s}']['ss_rmse']) for s in (0, 1, 2) if f'{v}|{s}' in res]); fails = sum(o != 'timeout' for s in (0, 1, 2) if f'{v}|{s}' in res for o in res[f'{v}|{s}']['outcome'])
        L2.append(f"| {v} | {', '.join(f'{p:.5f}' for p in per)} | {np.mean(per):.5f} +- {np.std(per):.5f} | {ss:.5f} | {100*m:+.1f}% [{100*lo:+.1f}%, {100*hi:+.1f}%] (positive = worse) | {label3(m, lo, hi)} | {fails} |")
    L2.append('')
L += L2
open(os.path.join(R, 'table.md'), 'w').write('\n'.join(L)); print('\n'.join(L2))
